import { afterEach, beforeEach, describe, expect, it, vi, type MockInstance } from 'vitest'
import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { MemoryRouter } from 'react-router-dom'
import { FaceLibraryPreview } from '@/features/faces/FaceLibraryPreview'
import { FaceHistoryPreview } from '@/features/faces/FaceHistoryPreview'
import { FaceSearchPreview } from '@/features/faces/FaceSearchPreview'

const network = vi.fn(() => { throw new Error('Face preview must not call production APIs') })
let storage: MockInstance<Storage['setItem']>
beforeEach(() => {
  vi.stubGlobal('fetch', network)
  network.mockClear()
  storage = vi.spyOn(Storage.prototype, 'setItem')
})
afterEach(() => {
  cleanup()
  expect(network).not.toHaveBeenCalled()
  expect(storage).not.toHaveBeenCalled()
  vi.restoreAllMocks()
  vi.unstubAllGlobals()
})
function library() { return render(<MemoryRouter><FaceLibraryPreview previewOnly /></MemoryRouter>) }
function createDraft() {
  fireEvent.click(screen.getByRole('button', { name: '新建人脸库草稿' }))
  fireEvent.change(screen.getByLabelText('库名称'), { target: { value: '访客复核草稿' } })
  fireEvent.change(screen.getByLabelText('名单有效期'), { target: { value: '2027-01-01' } })
  fireEvent.click(screen.getByLabelText('示例通道 A · 大门'))
}
function save() { fireEvent.click(screen.getByRole('button', { name: '保存到本次预览' })) }

describe('人脸库内存草稿', () => {
  it('显式预览、示例独立且不启用，刷新后不恢复草稿', () => {
    const view = library()
    expect(screen.getByText('设计预览 · 未接入后台')).toBeInTheDocument()
    expect(screen.getByRole('button', { name: '正式启用（后台未接入）' })).toBeDisabled()
    fireEvent.click(screen.getByRole('button', { name: '查看示例库布局' }))
    expect(screen.getByRole('article', { name: '只读示例库' })).toHaveTextContent('不加入下方草稿')
    expect(screen.getByText('暂无内存草稿')).toBeInTheDocument()
    createDraft(); save()
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(screen.getByRole('article', { name: '访客复核草稿' })).toHaveTextContent('草稿 v1')
    view.unmount(); library()
    expect(screen.getByText('暂无内存草稿')).toBeInTheDocument()
    expect(screen.queryByRole('article', { name: '访客复核草稿' })).not.toBeInTheDocument()
  })

  it.each(['取消', '关闭', 'Escape'])('%s 一致确认放弃，继续编辑保留输入，关闭后焦点返回入口', (action) => {
    library()
    const opener = screen.getByRole('button', { name: '新建人脸库草稿' })
    opener.focus(); createDraft()
    const close = () => action === 'Escape' ? fireEvent.keyDown(document, { key: 'Escape' }) : fireEvent.click(within(screen.getByRole('dialog', { name: '新建人脸库草稿' })).getByRole('button', { name: new RegExp(`^${action}$`) }))
    close()
    expect(screen.getByRole('dialog', { name: '放弃未保存的人脸库修改？' })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '继续编辑' }))
    expect(screen.getByLabelText('库名称')).toHaveValue('访客复核草稿')
    close()
    fireEvent.click(screen.getByRole('button', { name: '放弃修改' }))
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(screen.getByText('暂无内存草稿')).toBeInTheDocument()
    expect(opener).toHaveFocus()
  })

  it('无改动直接关闭，表单缺项不会保存', () => {
    library()
    fireEvent.click(screen.getByRole('button', { name: '新建人脸库草稿' }))
    fireEvent.keyDown(document, { key: 'Escape' })
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '新建人脸库草稿' }))
    save()
    expect(screen.getByRole('alert')).toHaveTextContent('请填写库名称')
    fireEvent.change(screen.getByLabelText('库名称'), { target: { value: '临时库' } }); save()
    expect(screen.getByRole('alert')).toHaveTextContent('至少一个')
    fireEvent.click(screen.getByLabelText('示例通道 A · 大门')); save()
    expect(screen.getByRole('alert')).toHaveTextContent('有效期')
  })

  it('编辑取消保留已存草稿；冲突保留输入，核对新版本后显式重试', () => {
    library(); createDraft(); save()
    fireEvent.click(screen.getByRole('button', { name: '编辑草稿' }))
    fireEvent.change(screen.getByLabelText('库名称'), { target: { value: '不应保存' } })
    fireEvent.click(screen.getByRole('button', { name: /^取消$/ }))
    fireEvent.click(screen.getByRole('button', { name: '放弃修改' }))
    expect(screen.getByRole('article', { name: '访客复核草稿' })).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '编辑草稿' }))
    fireEvent.change(screen.getByLabelText('库名称'), { target: { value: '冲突后保留的输入' } })
    fireEvent.click(screen.getByLabelText('下次保存模拟版本冲突')); save()
    expect(screen.getByRole('alert')).toHaveTextContent('输入已保留')
    expect(screen.getByLabelText('库名称')).toHaveValue('冲突后保留的输入')
    expect(screen.getByRole('article', { name: '访客复核草稿' })).toHaveTextContent('草稿 v1')
    // Unchecking injection must not silently resolve an outstanding conflict.
    fireEvent.click(screen.getByLabelText('下次保存模拟版本冲突')); save()
    expect(screen.getByRole('alert')).toHaveTextContent('模拟版本冲突')
    fireEvent.click(screen.getByRole('button', { name: '按新版本继续（保留输入）' }))
    expect(screen.getByLabelText('库名称')).toHaveValue('冲突后保留的输入')
    save()
    expect(screen.getByRole('article', { name: '冲突后保留的输入' })).toHaveTextContent('草稿 v3')
  })

  it('成员低质量可纠正，模型切换保留旧空间且不假称迁移完成', () => {
    library(); createDraft()
    fireEvent.click(screen.getByRole('button', { name: '添加占位成员' }))
    fireEvent.change(screen.getByLabelText('成员名称 1'), { target: { value: '占位成员' } })
    fireEvent.change(screen.getByLabelText('图片质量 1'), { target: { value: 'blurred' } })
    expect(screen.getByRole('article', { name: '成员 1' })).toHaveTextContent('不可用于匹配')
    fireEvent.change(screen.getByLabelText('图片质量 1'), { target: { value: 'qualified' } })
    expect(screen.getByRole('article', { name: '成员 1' })).toHaveTextContent('特征尚未提取')
    fireEvent.change(screen.getByLabelText('人脸特征空间'), { target: { value: 'r50-v1' } })
    expect(screen.getByText(/迁移待执行：已有成员引用旧空间/)).toBeInTheDocument()
    save()
    const card = screen.getByRole('article', { name: '访客复核草稿' })
    expect(card).toHaveTextContent('1 张模拟合格 / 1 张占位图')
    expect(card).toHaveTextContent('旧空间待迁移')
    expect(card).toHaveTextContent('历史版本引用不重写')
  })
})

describe('人脸抓拍与搜索共用示例结果', () => {
  it('真实查询未接入默认不展示例，质量和匹配状态分离，身份按模拟权限隐藏', () => {
    render(<MemoryRouter><FaceHistoryPreview previewOnly channelId="real-channel" /></MemoryRouter>)
    expect(screen.queryByRole('article')).not.toBeInTheDocument()
    expect(screen.getByText('真实人脸抓拍查询尚未接入')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '查看示例抓拍' }))
    expect(screen.getAllByRole('article')).toHaveLength(5)
    expect(screen.getByText(/不是唯一人数/)).toBeInTheDocument()
    expect(screen.queryByText('示例候选 01（非真实身份）')).not.toBeInTheDocument()
    expect(screen.getByRole('article', { name: 'demo-capture-02' })).toHaveTextContent('不等于陌生人')
    fireEvent.click(screen.getByLabelText('模拟授权查看示例身份'))
    expect(screen.getByText('示例候选 01（非真实身份）')).toBeInTheDocument()
    fireEvent.change(screen.getByLabelText('示例状态筛选'), { target: { value: 'unavailable' } })
    expect(screen.getAllByRole('article')).toHaveLength(3)
    expect(screen.getByRole('article', { name: 'demo-capture-04' })).toHaveTextContent('不能跨模型比较')
    expect(screen.getByRole('article', { name: 'demo-capture-05' })).toHaveTextContent('不是零命中')
    fireEvent.change(screen.getByLabelText('示例状态筛选'), { target: { value: 'unmatched' } })
    expect(screen.getAllByRole('article')).toHaveLength(1)
    fireEvent.click(screen.getByRole('button', { name: '查看示例详情' }))
    expect(screen.getByRole('dialog')).toHaveTextContent('demo-capture-02')
    expect(screen.getByRole('button', { name: '查看录像（未接入）' })).toBeDisabled()
    fireEvent.keyDown(document, { key: 'Escape' })
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(document.querySelector('img')).toBeNull()
  })

  it('本地文件检查不冒充人脸检测，模拟完成复用抓拍结果，清除即移除结果', async () => {
    render(<FaceSearchPreview previewOnly />)
    expect(screen.getByRole('button', { name: '正式搜索（后台未接入）' })).toBeDisabled()
    expect(screen.getByRole('button', { name: '模拟搜索流程' })).toBeDisabled()
    fireEvent.change(screen.getByLabelText('选择本地照片（不上传）'), { target: { files: [new File(['bytes'], 'test.jpg', { type: 'image/jpeg' })] } })
    expect(screen.getByText(/文件检查通过：test.jpg · 人脸质量尚未检测/)).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '模拟搜索流程' }))
    expect(screen.getByRole('status')).toHaveTextContent('未上传照片')
    await waitFor(() => expect(screen.getByRole('status')).toHaveTextContent('以下固定示例与所选照片无关'))
    expect(screen.getAllByRole('article')).toHaveLength(5)
    fireEvent.click(screen.getByRole('button', { name: '清除照片与结果' }))
    expect(screen.queryByRole('article')).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: '模拟搜索流程' })).toBeDisabled()
  })

  it('格式错误、取消和质量/覆盖不可用不产出假匹配', async () => {
    render(<FaceSearchPreview previewOnly />)
    const input = screen.getByLabelText('选择本地照片（不上传）')
    fireEvent.change(input, { target: { files: [new File(['abc'], 'bad.txt', { type: 'text/plain' })] } })
    expect(screen.getByRole('alert')).toHaveTextContent('格式不支持')
    expect(screen.getByRole('button', { name: '模拟搜索流程' })).toBeDisabled()
    fireEvent.change(input, { target: { files: [new File([], 'empty.jpg', { type: 'image/jpeg' })] } })
    expect(screen.getByRole('alert')).toHaveTextContent('非空')
    fireEvent.change(input, { target: { files: [new File(['abc'], 'face.png', { type: 'image/png' })] } })
    fireEvent.click(screen.getByRole('button', { name: '模拟搜索流程' }))
    fireEvent.click(screen.getByRole('button', { name: '取消模拟搜索' }))
    expect(screen.getByRole('status')).toHaveTextContent('照片已选择，可模拟流程')
    fireEvent.change(screen.getByLabelText('模拟人脸质量与索引状态'), { target: { value: 'blurred' } })
    fireEvent.click(screen.getByRole('button', { name: '模拟搜索流程' }))
    await waitFor(() => expect(screen.getByRole('status')).toHaveTextContent('模拟质量不合格'))
    expect(screen.queryByRole('article')).not.toBeInTheDocument()
    fireEvent.change(screen.getByLabelText('模拟人脸质量与索引状态'), { target: { value: 'uncovered' } })
    fireEvent.click(screen.getByRole('button', { name: '模拟搜索流程' }))
    await waitFor(() => expect(screen.getByRole('status')).toHaveTextContent('不代表零匹配'))
    expect(screen.queryByRole('article')).not.toBeInTheDocument()
  })
})
