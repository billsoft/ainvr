const observation = (change: Partial<SimulatedObservation> = {}): SimulatedObservation => ({ quality: 'valid', intervalMs: 1000, candidate: true, people: 0, ...change })
function openPreview() {
  const opener = screen.getByRole('button', { name: '新建场景 · 设计预览' })
  opener.focus(); fireEvent.click(opener)
  return opener
}
function changeField(name: string, value: string) { fireEvent.change(screen.getByLabelText(name), { target: { value } }) }
