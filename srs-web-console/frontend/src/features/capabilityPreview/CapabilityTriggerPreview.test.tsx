describe('design-only business semantics', () => {
  it('distinguishes unknown from a valid zero and restarts continuity after an outage', () => {
    const draft = { ...createPreviewDraft('understaffed'), durationSeconds: '3' }
    let result = simulateObservation(initialSimulation(), draft, observation({ intervalMs: 2000 }))
    expect(result.phase).toBe('pending')
    result = simulateObservation(result, draft, observation({ quality: 'unavailable', intervalMs: 60000 }))
    expect(result).toMatchObject({ phase: 'unknown', pendingMs: 0, episodes: 0 })
    result = simulateObservation(result, draft, observation({ intervalMs: 2000 }))
    expect(result).toMatchObject({ phase: 'pending', episodes: 0 })
    result = simulateObservation(result, draft, observation())
    expect(result).toMatchObject({ phase: 'active', episodes: 1 })
  })
  it.each([null, -1, 0.5, NaN])('cannot use missing or invalid count %s as zero', people => {
    const result = simulateObservation(initialSimulation(), createPreviewDraft('understaffed'), observation({ people, intervalMs: 60000 }))
    expect(result).toMatchObject({ phase: 'unknown', episodes: 0 })
  })
  it('uses strict below-minimum and continuous milliseconds rather than sample count', () => {
    expect(draftError({ ...createPreviewDraft(), durationSeconds: '1.001' })).toBe('')
    const draft = { ...createPreviewDraft('understaffed'), minimumPeople: '2', durationSeconds: '0.3' }
    expect(simulateObservation(initialSimulation(), draft, observation({ people: 2 })).phase).toBe('normal')
    let result = initialSimulation()
    for (let i = 0; i < 2; i++) result = simulateObservation(result, draft, observation({ people: 1, intervalMs: 100 }))
    expect(result.episodes).toBe(0)
    result = simulateObservation(result, draft, observation({ people: 1, intervalMs: 100 }))
    expect(result.episodes).toBe(1)
    expect(simulateObservation(initialSimulation(), draft, observation({ people: 1, intervalMs: 300 })).episodes).toBe(1)
  })
  it('keeps one regional episode through unknown, requires valid recovery, then permits a new episode', () => {
    const draft = { ...createPreviewDraft('fire'), durationSeconds: '2', recoverySeconds: '2' }
    let result = simulateObservation(initialSimulation(), draft, observation({ intervalMs: 2000 }))
    result = simulateObservation(result, draft, observation({ intervalMs: 2000 }))
    expect(result.episodes).toBe(1)
    result = simulateObservation(result, draft, observation({ candidate: false }))
    expect(result.phase).toBe('recovering')
    result = simulateObservation(result, draft, observation({ quality: 'stale', intervalMs: 10000, candidate: false }))
    expect(result).toMatchObject({ phase: 'unknown', episodeOpen: true, recoveryMs: 0, episodes: 1 })
    result = simulateObservation(result, draft, observation({ candidate: false }))
    expect(result.phase).toBe('recovering')
    result = simulateObservation(result, draft, observation({ candidate: false }))
    expect(result).toMatchObject({ phase: 'normal', episodeOpen: false, episodes: 1 })
    result = simulateObservation(result, draft, observation({ intervalMs: 2000 }))
    expect(result.episodes).toBe(2)
  })
  it.each(['helmet', 'fall'] as const)('requires explicit qualifying evidence for %s, not ambiguous association', scene => {
    const draft = createPreviewDraft(scene)
    expect(simulateObservation(initialSimulation(), draft, observation({ quality: 'ambiguous', intervalMs: 30000 })).phase).toBe('unknown')
    expect(simulateObservation(initialSimulation(), draft, observation({ candidate: false, intervalMs: 30000 })).episodes).toBe(0)
  })
  it('pose is observation only even after a long interval', () => {
    const result = simulateObservation(initialSimulation(), createPreviewDraft('pose'), observation({ intervalMs: 3600000 }))
    expect(result).toMatchObject({ phase: 'observation', episodes: 0, episodeOpen: false })
  })
  it.each([{ durationSeconds: '' }, { durationSeconds: '0' }, { recoverySeconds: 'Infinity' }, { minimumPeople: '0' }, { minimumPeople: '1.5' }])('rejects invalid draft %j', change => {
    const draft = { ...createPreviewDraft('understaffed'), ...change }
    expect(draftError(draft)).not.toBe('')
    expect(simulateObservation(initialSimulation(), draft, observation()).episodes).toBe(0)
  })
  it('summaries name candidate semantics and distinguish zero from unknown', () => {
    expect(previewSummary(createPreviewDraft('helmet'))).toContain('发现未戴安全帽的人员')
    expect(previewSummary(createPreviewDraft('fall'))).toContain('有人呈倒地姿态')
    expect(previewSummary(createPreviewDraft('understaffed'))).toContain('人数少于 1 人（无人）')
    expect(previewSummary(createPreviewDraft('fire'))).toContain('画面中断或看不清的时段不计时')
  })
})

